import type { SVGProps } from "react";

type IconProps = SVGProps<SVGSVGElement>;

// Sized like text (1em) and coloured by currentColor, so className controls both.
const make = (name: string, viewBox: string, body: string) => {
  const Icon = (props: IconProps) => (
    <svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" viewBox={viewBox} aria-hidden={props["aria-label"] ? undefined : true} {...props} dangerouslySetInnerHTML={{ __html: body }} />
  );
  Icon.displayName = name;
  return Icon;
};

